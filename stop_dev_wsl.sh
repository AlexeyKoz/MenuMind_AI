#!/bin/bash

# BishulMe Development Stop Script for WSL2

set -e

# Colors
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
RED='\033[0;31m'
NC='\033[0m' # No Color

echo ""
echo -e "${YELLOW}???????????????????????????????????????????????????????????????${NC}"
echo -e "${YELLOW}  ?? Stopping BishulMe Development Environment${NC}"
echo -e "${YELLOW}???????????????????????????????????????????????????????????????${NC}"
echo ""

# Check if containers are running
if ! docker compose -f docker-compose.dev.yml ps | grep -q "Up"; then
    echo -e "${YELLOW}??  No containers are running${NC}"
    exit 0
fi

echo -e "${CYAN}Stopping all services...${NC}"
docker compose -f docker-compose.dev.yml down

echo ""
echo -e "${GREEN}? All services stopped${NC}"
echo ""
echo -e "${CYAN}?? Current Status:${NC}"
docker compose -f docker-compose.dev.yml ps

echo ""
echo -e "${YELLOW}Note: Data is preserved in Docker volumes${NC}"
echo -e "${CYAN}To start again: ${YELLOW}./start_dev_wsl.sh${NC}"
echo ""
echo -e "${RED}To remove all data (fresh start): ${YELLOW}docker compose -f docker-compose.dev.yml down -v${NC}"
echo ""


